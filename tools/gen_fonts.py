"""Generate TFT_eSPI smooth fonts (VLW format) from TrueType fonts.

Output: src/ui/assets/fonts.h / fonts.cpp with one byte array per font,
loadable with tft.loadFont(array) / sprite.loadFont(array).

Usage (from the project root):
    python tools/gen_fonts.py

Requires Pillow. Source font: Roboto (Apache License 2.0), installed on
Windows in C:/Windows/Fonts. Override the folder with --font-dir.
"""

import argparse
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "src" / "ui" / "assets"

VLW_VERSION = 11

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
VIET_LOWER = (
    "aàáảãạăằắẳẵặâầấẩẫậ" "đ" "eèéẻẽẹêềếểễệ" "iìíỉĩị"
    "oòóỏõọôồốổỗộơờớởỡợ" "uùúủũụưừứửữự" "yỳýỷỹỵ"
)
VIET = VIET_LOWER + VIET_LOWER.upper()
DEGREE = "\u00b0"

TEXT_CHARS = ASCII + VIET + DEGREE
DIGIT_CHARS = " 0123456789-.:" + DEGREE + "C"

# (C++ symbol, TTF file, pixel size, character set)
FONTS = [
    ("kFontSmall", "Roboto-Regular.ttf", 15, TEXT_CHARS),
    ("kFontMedium", "Roboto-Medium.ttf", 20, TEXT_CHARS),
    ("kFontTemp", "Roboto-Medium.ttf", 46, DIGIT_CHARS),
    ("kFontClock", "Roboto-Medium.ttf", 26, DIGIT_CHARS),
]


def build_vlw(ttf_path: Path, size: int, chars: str) -> bytes:
    font = ImageFont.truetype(str(ttf_path), size)
    ascent, descent = font.getmetrics()
    codepoints = sorted(set(ord(c) for c in chars))

    metrics = []
    bitmaps = []
    for cp in codepoints:
        ch = chr(cp)
        advance = round(font.getlength(ch))
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        width, height = right - left, bottom - top
        if cp == 0x20 or width <= 0 or height <= 0:
            metrics.append((cp, 0, 0, advance, 0, 0))
            bitmaps.append(b"")
            continue
        if width > 255 or height > 255:
            raise ValueError(f"glyph U+{cp:04X} too large for VLW")
        img = Image.new("L", (width, height), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        metrics.append((cp, height, width, advance, -top, left))
        bitmaps.append(img.tobytes())

    out = bytearray()
    out += struct.pack(">6i", len(codepoints), VLW_VERSION, size, 0, ascent, descent)
    for cp, h, w, adv, dy, dx in metrics:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for bmp in bitmaps:
        out += bmp
    return bytes(out)


def to_c_array(name: str, data: bytes) -> str:
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", default="C:/Windows/Fonts")
    args = parser.parse_args()
    font_dir = Path(args.font_dir)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    header = [
        "// Generated by tools/gen_fonts.py - do not edit.",
        "// Roboto, Apache License 2.0. TFT_eSPI smooth font (VLW) arrays.",
        "#pragma once",
        "",
        "#include <pgmspace.h>",
        "#include <stdint.h>",
        "",
    ]
    source = [
        "// Generated by tools/gen_fonts.py - do not edit.",
        '#include "fonts.h"',
        "",
    ]
    for name, ttf, size, chars in FONTS:
        data = build_vlw(font_dir / ttf, size, chars)
        header.append(f"extern const uint8_t {name}[];  // {ttf} {size}px, {len(data)} bytes")
        source.append(to_c_array(name, data))
        source.append("")
        print(f"{name}: {ttf} {size}px, {len(set(chars))} glyphs, {len(data)} bytes")

    (OUT_DIR / "fonts.h").write_text("\n".join(header) + "\n", encoding="utf-8", newline="\n")
    (OUT_DIR / "fonts.cpp").write_text("\n".join(source), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
