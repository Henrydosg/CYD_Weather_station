"""Generate the TIME FALLS smooth fonts (VLW) -> src/timefalls/assets/tf_fonts.*

Roboto Bold for the time (digits only); the small text reuses the weather
station's fonts. Uses build_vlw() from gen_fonts.py (Pillow required).

One source per size class like gen_fonts.py: tf_fonts.cpp (2.8"),
tf_fonts_m.cpp (3.5", sizes x 4/3).

Usage (from the project root):
    python tools/gen_tf_fonts.py [--font-dir C:/Windows/Fonts]
"""

import argparse
from pathlib import Path

from gen_fonts import CLASSES, build_vlw, class_size, to_c_array

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "src" / "timefalls" / "assets"

# Small text uses the weather station's fonts (src/ui/assets, with Vietnamese).
FONTS = [
    ("kTfFontTime", "Roboto-Bold.ttf", 68, " 0123456789:-"),
]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font-dir", default="C:/Windows/Fonts")
    args = ap.parse_args()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    header = ["// Generated by tools/gen_tf_fonts.py - do not edit.",
              "// Roboto, Apache License 2.0. TFT_eSPI smooth font (VLW) arrays.",
              "#pragma once", "", "#include <pgmspace.h>", "#include <stdint.h>", ""]
    sizes = {name: [] for name, _, _, _ in FONTS}
    for suffix, scale, cond in CLASSES:
        source = ["// Generated by tools/gen_tf_fonts.py - do not edit.", '#include "tf_fonts.h"',
                  "", f"#if {cond}", ""]
        for name, ttf, size, chars in FONTS:
            px = class_size(size, scale)
            data = build_vlw(Path(args.font_dir) / ttf, px, chars)
            sizes[name].append(f"{px}px {len(data)} B")
            source += [to_c_array(name, data), ""]
            print(f"{name}{suffix}: {ttf} {px}px, {len(set(chars))} glyphs, {len(data)} bytes")
        source.append(f"#endif  // {cond}")
        (OUT_DIR / f"tf_fonts{suffix}.cpp").write_text("\n".join(source) + "\n", encoding="utf-8",
                                                        newline="\n")
    for name, ttf, _, _ in FONTS:
        header.append(f"extern const uint8_t {name}[];  // {ttf}, S {sizes[name][0]} / "
                      f"M {sizes[name][1]}")
    (OUT_DIR / "tf_fonts.h").write_text("\n".join(header) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
